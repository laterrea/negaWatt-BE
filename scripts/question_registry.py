#!/usr/bin/env python
"""Write docs/workshop_question_ids.md: every question id that can hold answers.

    python scripts/question_registry.py            # rewrite the registry
    python scripts/question_registry.py --check    # fail if it is out of date

The database stores an answer as (group, question id, value): the id is the only
link between a stored number and the question that was asked. This registry lists,
for every id that exists or ever existed:

  * the questions defined today, with their unit, the file that words them, the
    answer ids of their sliders, the line-ups that play them, and the older ids
    they stand for (`model.supersedes` in the lever module);
  * the ids retired before line-ups existed (programme.yaml, `retired:`), with the
    unit they were answered in and the git commit that still defines them.

Reads website/data/levers_*.js, website/workshop/content/*.yaml and
programme.yaml. See docs/workshop_module.md, D69-D72.
"""
import argparse
import glob
import json
import os
import re
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONTENT = os.path.join(ROOT, "website", "workshop", "content")
DATA = os.path.join(ROOT, "website", "data")
OUT = os.path.join(ROOT, "docs", "workshop_question_ids.md")


def generated(path):
    text = open(path, encoding="utf-8").read()
    return json.loads(re.search(r"= (\{.*\});\s*\Z", text, re.S).group(1))


def render():
    programme = yaml.safe_load(open(os.path.join(CONTENT, "programme.yaml"),
                                    encoding="utf-8")) or {}
    lineups = programme.get("lineups") or {}
    active = programme.get("active")

    homes, files = {}, {}
    for path in sorted(glob.glob(os.path.join(CONTENT, "*.yaml"))):
        name = os.path.basename(path)
        if name in ("ui.yaml", "programme.yaml"):
            continue
        doc = yaml.safe_load(open(path, encoding="utf-8")) or {}
        files[doc.get("topic")] = (name, doc)
        for lid, block in (doc.get("levers") or {}).items():
            homes[lid] = (doc.get("topic"), name, block)

    def played_in(lid, topic):
        out = []
        for lname, entry in lineups.items():
            for tid, spec in ((entry or {}).get("topics") or {}).items():
                ids = (list((files.get(tid, ("", {}))[1].get("levers") or {}))
                       if spec == "all" else list(spec or []))
                if lid in ids:
                    label = f"`{lname}`" + ("" if tid == topic else f" (in `{tid}`)")
                    out.append(label + (" ★" if lname == active else ""))
        return ", ".join(out) or "— (archived)"

    lines = [
        "# Workshop question ids",
        "",
        "*Generated by `scripts/question_registry.py` — do not edit by hand.*",
        "",
        "The workshop database stores each answer as (group, question id, value): the id is",
        "the only link between a stored number and the question that was asked. A group",
        "also stores the theme it played (`ws_groups.topic`). This page lists every id that",
        "can hold answers, so that any row of `ws_answers` / `ws_answer_log` can be read.",
        "",
        "- A question answered with several sliders stores the combined figure under its",
        "  own id and each slider under `<id>__<part>`.",
        "- Ids are never reused: a question whose unit or meaning changes gets a new id, and",
        "  the old one stays here (D62, D69).",
        f"- ★ marks the active line-up (`{active}`). A question played in no line-up is",
        "  *archived*: still defined and worded, shown by the reveal for the sittings that",
        "  answered it.",
        "",
    ]
    for sector_file in sorted(glob.glob(os.path.join(DATA, "levers_*.js"))):
        data = generated(sector_file)
        sector = os.path.basename(sector_file)[len("levers_"):-3]
        by_topic = {}
        for lid, lv in data["levers"].items():
            by_topic.setdefault(lv.get("topic"), []).append((lid, lv))
        for topic, items in by_topic.items():
            lines += [f"## `{topic}` (sector `{sector}`)", "",
                      "| id | question (fr) | unit | answer ids of its sliders | played in | stands for |",
                      "|---|---|---|---|---|---|"]
            for lid, lv in items:
                home = homes.get(lid)
                if not lv.get("shown"):
                    question = "*spare lever, no wording, never played*"
                elif home is None:
                    question = "*no wording (build error)*"
                else:
                    question = (home[2].get("question") or {}).get("fr", "").strip()
                    question = question.replace("|", "\\|").replace("\u00a0", " ")
                parts = ", ".join(f"`{p['answerId']}` ({p['unit']})"
                                  for p in lv.get("parts") or []) or "—"
                stands = ", ".join(f"`{x}`" for x in (lv.get("model") or {})
                                   .get("supersedes", [])) or "—"
                where = played_in(lid, topic) if lv.get("shown") else "—"
                lines.append(f"| `{lid}` | {question} | {lv['unit']} | {parts} | {where} | {stands} |")
            lines.append("")

    composite = [(tid, f[0], f[1].get("include")) for tid, f in files.items()
                 if f[1].get("include") is not None]
    if composite:
        lines += ["## Themes made of other themes' questions (D70)", "",
                  "Their groups are stored under their own topic id; the questions keep their",
                  "ids, so the same question id can hold answers under several topics.", "",
                  "| topic | file | includes |", "|---|---|---|"]
        lines += [f"| `{tid}` | `{name}` | {', '.join(f'`{t}`' for t in inc)} |"
                  for tid, name, inc in composite]
        lines.append("")

    retired = programme.get("retired") or {}
    lines += ["## Retired ids (no longer defined anywhere)", "",
              "Answers stored under these ids belong to questions removed before line-ups",
              "existed. `git show <commit>:website/data/levers_<sector>.js` gives the full",
              "definition, `git show <commit>:website/workshop/content/<topic>.yaml` the wording.",
              "",
              "| id | topic | unit answered in | last defined in | replaced by | why |",
              "|---|---|---|---|---|---|"]
    for rid, info in retired.items():
        lines.append(f"| `{rid}` | `{info.get('topic', '')}` | {info.get('unit', '')} | "
                     f"`{info.get('commit', '')}` | "
                     f"{', '.join(f'`{x}`' for x in info.get('replacedBy') or []) or '—'} | "
                     f"{info.get('why', '')} |")
    lines.append("")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = ap.parse_args()
    text = render()
    if args.check:
        current = open(OUT, encoding="utf-8").read() if os.path.isfile(OUT) else ""
        if current != text:
            print(f"{os.path.relpath(OUT, ROOT)} is out of date — run "
                  f"python scripts/question_registry.py", file=sys.stderr)
            return 1
        print("question registry up to date")
        return 0
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
